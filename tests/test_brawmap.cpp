// Tests for the camera-metadata projection seam (src/BRAWLensMap.h): the
// minimal calibration-JSON parser and the Mei-Rives map generator that turn
// an URSA Cine Immersive clip's embedded Apple Immersive calibration into
// per-eye equirect STMaps.
//
// The fixture (tests/fixtures/ursa_immersive_calibration.json) is the real
// OpticalProjectionData blob from an URSA Cine Immersive clip. Golden values
// were produced by an independent double-precision Python implementation of
// the same spec (gen_goldens.py in docs/captures/; first verified against
// decoded frames of that clip, docs/2026-08-30-braw-immersive-metadata-
// projection.md; rectification convention re-pinned 2026-10-28 by stereo
// measurement on underwater-housing footage, LEARNINGS.md). Build & run:
// make test
#include "BRAWLensMap.h"

#include <algorithm>
#include <clocale>
#include <cmath>
#include <cstdio>
#include <string>
#include <vector>

static int failures = 0;

static void check(bool ok, const char* name)
{
    if (!ok) {
        ++failures;
        std::fprintf(stderr, "FAIL %s\n", name);
    } else {
        std::printf("ok   %s\n", name);
    }
}

static void expectNear(double actual, double expected, double tolerance, const char* name)
{
    if (std::isnan(actual) || std::fabs(actual - expected) > tolerance) {
        ++failures;
        std::fprintf(stderr, "FAIL %s\n  expected: %.9f (±%g)\n  actual:   %.9f\n",
                     name, expected, tolerance, actual);
    } else {
        std::printf("ok   %s\n", name);
    }
}

static bool loadFile(const char* path, std::string* out)
{
    std::FILE* f = std::fopen(path, "rb");
    if (!f) return false;
    std::fseek(f, 0, SEEK_END);
    const long size = std::ftell(f);
    std::fseek(f, 0, SEEK_SET);
    if (size <= 0) {
        std::fclose(f);
        return false;
    }
    out->resize(static_cast<size_t>(size));
    const bool ok = std::fread(&(*out)[0], 1, out->size(), f) == out->size();
    std::fclose(f);
    return ok;
}

static const float* texel(const ndi_stmap::STMapImage& map, int r, int c)
{
    return map.uv.data() + (static_cast<size_t>(r) * map.width + c) * 2;
}

int main()
{
    std::string json;
    if (!loadFile("tests/fixtures/ursa_immersive_calibration.json", &json)) {
        std::fprintf(stderr, "FAIL cannot read tests/fixtures/ursa_immersive_calibration.json "
                             "(run from the repo root: make test)\n");
        return 1;
    }

    // ---- parse the real calibration -------------------------------------
    ndi_brawmap::LensCalibration cal;
    std::string error;
    check(ndi_brawmap::parseCalibrationJSON(json, &cal, &error), "fixture parses");
    if (failures) {
        std::fprintf(stderr, "  parse error: %s\n", error.c_str());
        return failures;
    }
    check(cal.generator == "Apple Immersive Camera Calibration Service", "generator string");
    expectNear(cal.left.fx, 7765.9024452131525, 1e-6, "left fx");
    expectNear(cal.left.cx, 4080.2881365398475, 1e-6, "left centerX");
    expectNear(cal.left.xi, 2.0429670816469443, 1e-9, "left xi (3rd distortion)");
    expectNear(cal.left.skew, -0.6674811051990651, 1e-9, "left skew");
    expectNear(cal.left.calibLimitDeg, 109.58572387695312, 1e-6, "left calibration limit");
    check(cal.left.imageWidth == 8160 && cal.left.imageHeight == 7200, "left imageSize");
    expectNear(cal.right.fx, 7750.7705728515775, 1e-6, "right fx");
    expectNear(cal.left.quat[3], 0.9999883522213009, 1e-9, "left quat w");
    expectNear(cal.left.maskRadiusDeg, 80.0, 1e-3, "mask circle radius");
    check(cal.left.maskSpreadDeg < 0.01, "mask ring is circular (spread ~0)");
    expectNear(cal.left.maskEdgeDeg, 2.5, 1e-9, "mask edge width");

    // ---- pure projection golden: a ray at half the stated horizontal FOV
    // must land on the sensor edge (the check that pinned the model).
    {
        const double theta = 101.832221984863281 * (M_PI / 180.0);
        ndi_brawmap::MeiProjector projector(cal.left);
        double uPx = 0, vPx = 0;
        check(projector.project(std::sin(theta), 0.0, std::cos(theta), &uPx, &vPx),
              "half-hFov ray projects");
        expectNear(uPx, 8165.5523, 0.05, "half-hFov ray lands at the sensor edge");
    }

    // ---- full-chain goldens (rotation + projection + STMap normalize) ----
    ndi_stmap::STMapImage left, right;
    check(ndi_brawmap::generateLensMaps(cal, 64, false, &left, &right, &error),
          "maps generate at 64 (mask off)");
    check(left.width == 64 && left.height == 64 && right.width == 64, "map dimensions");

    struct Golden { int eye, r, c; float u, v; };
    // Generated by gen_goldens.py (double precision, independent implementation).
    static const Golden kGoldens[] = {
        { 0, 31, 31, 0.490438010f, 0.511267763f },
        { 0, 10, 50, 0.655640143f, 0.896442634f },
        { 0, 55, 20, 0.413848627f, 0.094067977f },
        { 0, 0, 0, 0.489406090f, 1.022142880f },
        { 0, 63, 63, 0.511095900f, -0.018125504f },
        { 0, 31, 0, 0.045708973f, 0.513189008f },
        { 1, 31, 31, 0.490441669f, 0.511518846f },
        { 1, 10, 50, 0.655604886f, 0.897331336f },
        { 1, 55, 20, 0.413727849f, 0.094994924f },
        { 1, 0, 0, 0.489041650f, 1.023662734f },
        { 1, 63, 63, 0.510706796f, -0.016769303f },
        { 1, 31, 0, 0.044992383f, 0.513723843f },
    };
    for (const Golden& g : kGoldens) {
        const ndi_stmap::STMapImage& map = g.eye ? right : left;
        const float* t = texel(map, g.r, g.c);
        char name[128];
        std::snprintf(name, sizeof(name), "golden %s (%d,%d) u", g.eye ? "right" : "left", g.r, g.c);
        expectNear(t[0], g.u, 1e-5, name);
        std::snprintf(name, sizeof(name), "golden %s (%d,%d) v", g.eye ? "right" : "left", g.r, g.c);
        expectNear(t[1], g.v, 1e-5, name);
    }

    // The two eyes' calibrations genuinely differ (distinct intrinsics and
    // rectification) — a swapped or shared-eye bug would collapse them.
    // Compared over the whole map: rectified, the eyes' center texels land
    // within a fraction of a pixel of each other in u.
    {
        float maxDiff = 0.0f;
        for (size_t i = 0; i < left.uv.size(); ++i) {
            maxDiff = std::max(maxDiff, std::fabs(left.uv[i] - right.uv[i]));
        }
        check(maxDiff > 1e-3f, "left and right maps differ");
    }

    // The extreme corner projects geometrically fine but lands above the
    // fisheye frame (v > 1): the value is passed through for the warp's
    // own out-of-range handling, not flagged invalid here.
    check(texel(left, 0, 0)[0] >= 0.0f && texel(left, 0, 0)[1] > 1.0f,
          "corner texel is valid-but-out-of-frame");

    // ---- mask ------------------------------------------------------------
    ndi_stmap::STMapImage leftMasked, rightMasked;
    check(ndi_brawmap::generateLensMaps(cal, 64, true, &leftMasked, &rightMasked, &error),
          "maps generate at 64 (mask on)");
    check(texel(leftMasked, 31, 31)[0] >= 0.0f, "mask keeps the center");
    check(texel(leftMasked, 0, 31)[0] == -1.0f && texel(leftMasked, 0, 31)[1] == -1.0f,
          "mask cuts the top edge (88.6° > 80°)");
    check(texel(leftMasked, 31, 0)[0] == -1.0f, "mask cuts the left edge");
    check(texel(leftMasked, 5, 5)[0] == -1.0f, "mask cuts the corner region");
    // Inside the porthole the mask must not perturb the mapping.
    check(texel(leftMasked, 31, 31)[0] == texel(left, 31, 31)[0] &&
          texel(leftMasked, 31, 31)[1] == texel(left, 31, 31)[1],
          "mask leaves interior texels untouched");

    // ---- fail-soft paths -------------------------------------------------
    ndi_brawmap::LensCalibration scratch;
    error.clear();
    check(!ndi_brawmap::parseCalibrationJSON(json.substr(0, json.size() / 2), &scratch, &error) &&
              !error.empty(),
          "truncated JSON fails soft");
    error.clear();
    check(!ndi_brawmap::parseCalibrationJSON("this is not json", &scratch, &error) && !error.empty(),
          "garbage fails soft");
    error.clear();
    check(!ndi_brawmap::parseCalibrationJSON("{\"captureDevice\":{\"views\":[]}}", &scratch, &error) &&
              !error.empty(),
          "missing views fails soft");
    {
        std::string wrongModel = json;
        const std::string needle = "radial2ProjectionOffsetTangential2";
        for (size_t at = wrongModel.find(needle); at != std::string::npos;
             at = wrongModel.find(needle, at)) {
            wrongModel.replace(at, needle.size(), "someFutureLensModel1234567890abcde");
        }
        error.clear();
        check(!ndi_brawmap::parseCalibrationJSON(wrongModel, &scratch, &error) &&
                  error.find("unsupported lens model") != std::string::npos,
              "unknown lens model fails soft with a clear error");
    }
    {
        std::string deep(ndi_brawmap::kMaxJsonDepth + 8, '[');
        error.clear();
        check(!ndi_brawmap::parseCalibrationJSON(deep, &scratch, &error) && !error.empty(),
              "hostile nesting fails soft");
    }
    {
        ndi_stmap::STMapImage bad;
        error.clear();
        check(!ndi_brawmap::generateEyeMap(cal.left, 4, false, &bad, &error) && !error.empty(),
              "undersized map request fails soft");
    }

    // ---- standalone ILPD files -------------------------------------------
    // tests/fixtures/custom_rig.ilpd is synthetic, laid out like the generic
    // ILPDs Resolve ships (square 7200² sensor, no calibrationLimitRadialAngle)
    // with an identity left rectification so its center is analytic.
    check(ndi_brawmap::isILPDPath("/rigs/custom_rig.ilpd"), "isILPDPath: .ilpd");
    check(ndi_brawmap::isILPDPath("C:\\rigs\\cam.4f1e.ILPD"), "isILPDPath: case-insensitive");
    check(!ndi_brawmap::isILPDPath("/clips/A001.braw"), "isILPDPath: .braw is not ILPD");
    check(!ndi_brawmap::isILPDPath("/rigs/custom_rig.ilpd.braw"), "isILPDPath: extension must be last");
    check(!ndi_brawmap::isILPDPath(".ilpd") && !ndi_brawmap::isILPDPath("ilpd") &&
              !ndi_brawmap::isILPDPath(""),
          "isILPDPath: bare extension / empty is not a file");
    {
        std::string ilpdJson;
        error.clear();
        const bool read = ndi_brawmap::readILPDFile("tests/fixtures/custom_rig.ilpd", &ilpdJson, &error);
        check(read, "ILPD fixture reads");
        ndi_brawmap::LensCalibration rig;
        const bool parsed = read && ndi_brawmap::parseCalibrationJSON(ilpdJson, &rig, &error);
        check(parsed, "ILPD fixture parses");
        if (!parsed) std::fprintf(stderr, "  ILPD error: %s\n", error.c_str());
        if (parsed) {
            check(rig.generator == "Synthetic custom-rig fixture (NDIOutput tests)", "ILPD generator");
            check(rig.left.imageWidth == 7200 && rig.left.imageHeight == 7200, "ILPD imageSize");
            expectNear(rig.left.calibLimitDeg, 180.0, 1e-12,
                       "absent calibrationLimitRadialAngle leaves the full sphere");
            expectNear(rig.right.cx, 3610.0, 1e-12, "ILPD right eye keeps its own intrinsics");
            expectNear(rig.left.maskRadiusDeg, 75.0, 1e-3, "ILPD mask circle radius");

            // Odd size puts a texel exactly on lon = lat = 0: with identity
            // rectification it must sample the principal point.
            ndi_stmap::STMapImage rigLeft, rigRight;
            check(ndi_brawmap::generateLensMaps(rig, 65, false, &rigLeft, &rigRight, &error),
                  "ILPD maps generate");
            expectNear(texel(rigLeft, 32, 32)[0], (3600.0 + 0.5) / 7200.0, 1e-6,
                       "ILPD center texel u = principal point");
            expectNear(texel(rigLeft, 32, 32)[1], 1.0 - (3600.0 + 0.5) / 7200.0, 1e-6,
                       "ILPD center texel v = principal point");
            // The right eye's quat is a pure +1° y rotation, like the
            // opposite ±3° y terms underwater-housing ILPDs carry. The quat
            // lives in visionOS's y-up/z-back frame, so in our x-right/z-fwd
            // rig frame it turns the camera toward -x: the rig-forward ray
            // lands LEFT of the principal point (the plain CV reading puts
            // it right, which diverged real housing footage ~11°).
            {
                const double th = 2.0 * std::asin(0.0087265 / std::sqrt(0.0087265 * 0.0087265 +
                                                                          0.9999619 * 0.9999619));
                const double mx = -std::sin(th) / (std::cos(th) + 1.9);
                const double radial = 1.0 - 0.1 * mx * mx + 0.2 * mx * mx * mx * mx;
                expectNear(texel(rigRight, 32, 32)[0], (5000.0 * radial * mx + 3610.0 + 0.5) / 7200.0, 1e-6,
                           "ILPD pure-y quat yaws the right eye toward -x (visionOS frame)");
                check(texel(rigRight, 32, 32)[0] < (3610.0 + 0.5) / 7200.0,
                      "ILPD rig-forward lands left of the right principal point");
                expectNear(texel(rigRight, 32, 32)[1], 1.0 - (3600.0 + 0.5) / 7200.0, 1e-6,
                           "ILPD pure-y quat leaves the center row level");
            }
        }
    }
    {
        std::string bomJson;
        ndi_brawmap::LensCalibration rig;
        error.clear();
        check(ndi_brawmap::readILPDFile("tests/fixtures/custom_rig_bom.ilpd", &bomJson, &error) &&
                  ndi_brawmap::parseCalibrationJSON(bomJson, &rig, &error),
              "ILPD with a UTF-8 BOM parses");
    }
    {
        std::string missing;
        error.clear();
        check(!ndi_brawmap::readILPDFile("tests/fixtures/does_not_exist.ilpd", &missing, &error) &&
                  error.find("cannot open") != std::string::npos,
              "missing ILPD fails soft");
        error.clear();
        check(!ndi_brawmap::readILPDFile("", &missing, &error) && !error.empty(),
              "empty ILPD path fails soft");
    }

    // ---- locale independence --------------------------------------------
    // strtod-based parsing breaks in comma-decimal locales; ours must not.
    if (std::setlocale(LC_NUMERIC, "de_DE.UTF-8") != nullptr ||
        std::setlocale(LC_NUMERIC, "de_DE") != nullptr) {
        ndi_brawmap::LensCalibration localeCal;
        error.clear();
        const bool ok = ndi_brawmap::parseCalibrationJSON(json, &localeCal, &error);
        check(ok, "parses under a comma-decimal locale");
        if (ok) {
            expectNear(localeCal.left.fx, 7765.9024452131525, 1e-6,
                       "numbers survive a comma-decimal locale");
        }
        std::setlocale(LC_NUMERIC, "C");
    } else {
        std::printf("ok   (locale test skipped — de_DE unavailable)\n");
    }

    if (failures) {
        std::fprintf(stderr, "%d FAILURE%s\n", failures, failures == 1 ? "" : "S");
    } else {
        std::printf("all brawmap tests passed\n");
    }
    return failures;
}
